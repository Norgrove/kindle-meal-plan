"""Recipe pool for the weekly plan.

The rules the pool must satisfy live in rules.toml; generate.py checks every
recipe against them. This file only holds the recipes and the shop layout.

Quantities are per person and metric: grams, millilitres, or a plain count.
How many people a meal serves comes from rules.toml (breakfast and lunch 1,
dinner 2), and batch lunches multiply by the days they cover. Ingredients are
written as you buy them (dry rice, drained tins), so the shopping list can add
them up. A fourth "optional" field marks an extra you can leave out.

Each recipe has a `group`: the breakfast type, "batch" or "sandwich" for
lunches, the protein for dinners (salmon, fish or plant), "shake" for the
protein shake. Dinners also carry a cuisine. Protein figures are rounded
estimates per person.
"""

