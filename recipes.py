def R(rid, name, protein, kind, prep, cook, ing, steps, group, cuisine=None, husband=None, tags=()):
    return {"id": rid, "name": name, "protein": protein, "kind": kind, "prep": prep, "cook": cook,
            "ing": [i if len(i) == 4 else (*i, None) for i in ing], "steps": steps,
            "group": group, "cuisine": cuisine, "husband": husband, "tags": set(tags)}


